#!/usr/bin/env python3
"""Generates sql/initial_inventory.sql from the CSV of objects provided by the
professor (columns: id, nombre, descripcion). The objects are inserted without
an owner: they are the market's initial inventory.

    python3 scripts/csv_to_inventory.py data/categoria18.csv > sql/initial_inventory.sql

Validates every row and fails without writing anything if one is invalid.
Development tooling only; it is not part of the application.
"""
import csv
import sys

MAX_NAME = 100        # objects.name VARCHAR(100)
MAX_DESCRIPTION = 1000  # objects.description VARCHAR(1000)


def sql_string(text):
    # Single-quoted SQL literal. Backslashes are escaped too, because MariaDB
    # treats them as escape characters inside strings by default.
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def fail(message):
    sys.exit(f"error: {message}")


def main(path):
    with open(path, encoding="utf-8-sig", newline="") as handle:  # utf-8-sig drops the BOM
        reader = csv.DictReader(handle)
        if reader.fieldnames != ["id", "nombre", "descripcion"]:
            fail(f"unexpected columns: {reader.fieldnames}")
        rows, seen = [], set()
        for line, row in enumerate(reader, start=2):
            try:
                object_id = int(row["id"])
            except ValueError:
                fail(f"line {line}: id is not an integer")
            name, description = row["nombre"].strip(), row["descripcion"].strip()
            if object_id <= 0 or object_id in seen:
                fail(f"line {line}: invalid or repeated id {object_id}")
            if not name or len(name) > MAX_NAME or len(description) > MAX_DESCRIPTION:
                fail(f"line {line}: name or description empty or too long")
            if any(ord(c) < 32 for c in name + description):
                fail(f"line {line}: control characters are not allowed")
            seen.add(object_id)
            rows.append((object_id, name, description))

    if not rows:
        fail("the file has no objects")

    print("SET NAMES utf8mb4;")
    print()
    print(f"-- Initial market inventory: {len(rows)} objects from {path.split('/')[-1]}.")
    print("-- Generated by scripts/csv_to_inventory.py. Do not edit by hand.")
    print("-- Run as root on VMDatos, on an objects table without development data:")
    print("--   sudo mariadb jesterschest < initial_inventory.sql")
    print("-- The whole load is one transaction: it inserts all objects or none.")
    print()
    print("START TRANSACTION;")
    print()
    print("INSERT INTO objects (object_id, name, description, owner_id, last_transfer_at) VALUES")
    values = [f"    ({i}, {sql_string(n)}, {sql_string(d)}, NULL, NULL)" for i, n, d in rows]
    print(",\n".join(values) + ";")
    print()
    print("COMMIT;")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
